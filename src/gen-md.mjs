import fs from 'node:fs';
import path from 'node:path';
import {
  meta, advisors, decisions, budget, phases, weekly, coreLib, days, dessert,
  forbidden, redFlags, painTree, tests, nutrition, phoneMethods, sources,
} from './data.mjs';

const ROOT = '/Users/mac/Desktop/健身计划';
const P = [];
const L = (...x) => P.push(...x);
const tbl = (head, rows) => {
  L('| ' + head.join(' | ') + ' |');
  L('|' + head.map(() => '---').join('|') + '|');
  rows.forEach((r) => L('| ' + r.join(' | ') + ' |'));
  L('');
};

L(`# ${meta.cn}`, '');
L(`> ${meta.sub}`, '');
L(`版本 ${meta.ver} ｜ 周期 16 周（3 个月版：停在第 12 周）｜ 每周 4 练 + 1 个可选甜点日`, '');
L('---', '');

L('## 00 先读这一页', '');
L('- **这不是医疗建议。** 前提：已获手术医生/康复师运动许可，当前无进行性神经症状。出现小腿麻木、放射痛、单侧无力、鞍区麻木或大小便功能改变 → 立即停练就医。', '- 核心占每天 22–28 分钟 / 总 72–75 分钟，即 **30%–38%**，每天都有、均匀摊开。', '- 腿部 **全部单腿**，主线无任何高轴向压缩杠铃动作。', '- 每天只做「当天那张表 + 当前分期那一列」。', '');

L('## 01 三位顾问', '');
advisors.forEach((a) => {
  L(`### ${a.name} · ${a.role}`, '');
  L(`*${a.cred}*`, '');
  L(`> 「${a.quote}」`, '');
  a.rules.forEach((r) => L(`- ${r}`));
  L('');
});

L('## 02 三人决策会议：五场冲突的裁决', '');
tbl(['议题', '冲突', '裁决（执行方案）'], decisions.map((d) => [d.topic, d.conf, d.res]));

L('## 03 设计逻辑', '');
L('### 3.1 时间预算', '');
tbl(['训练日', '总时长', '核心时长', '核心占比', '备注'], budget.map((b) => [b.day, b.total + ' 分钟', b.core + ' 分钟', Math.round((b.core / b.total) * 100) + '%', b.note || '—']));
L('### 3.2 十六周分期', '');
tbl(['分期', '周次', '名称', '目标', '关键参数', '降量'], phases.map((p) => [p.id, p.weeks, p.name, p.goal, p.key, p.deload]));
L('### 3.3 每周排程', '');
tbl(['星期', '日号', '安排'], weekly.map((w) => [w.d, w.w, w.t]));
L('> **排程铁律：** D1 与 D3 之间至少隔 48 小时。只能连排时，宁可按 D1→D2→D3→D4 四天连排，也不要一天两个下肢日。', '');

L('### 3.4 为什么腿全部单腿', '');
L('- 同等刺激下单腿动作的负重只有双腿的一半左右，脊柱轴向压缩远低于背蹲与双腿大重量腿举。', '- 四分卫出手就是「前腿承重 + 后腿蹬转」，单腿训练直接复刻这个姿态。', '- 单腿动作天然要求核心抗侧屈与抗旋转，等于下肢训练顺带练核心。', '- 哑铃/壶铃对侧手持，重心在体侧对称分布，不像杠铃那样直上直下压节段。', '');

L('### 3.5 核心如何均匀摊到每天', '');
tbl(['类别', 'D1', 'D2', 'D3', 'D4', 'D5'], [
  ['① 抗伸展', '负重死虫', '半跪腹轮 / 平板肩拍', '死虫（长杠杆）', '平板肩拍', '死虫 8/侧'],
  ['② 抗侧屈', '手提箱行走', '侧板 + 上举腿', '手提箱等长 / 单臂农夫走', '—', '侧板 20s/侧'],
  ['③ 抗旋转', '半跪 Pallof', '半跪 Cable Chop', '单臂农夫走', '半跪 Pallof / 单臂下拉', '鸟狗 8/侧'],
  ['④ 旋转爆发', '药球旋转抛', '—', '药球旋转抛 / 侧抛', '分腿姿药球旋转抛', '四向药球全谱'],
  ['⑤ 髋伸后链', '单腿臀桥 / 鸟狗', '90/90 呼吸重置', '俯卧背伸等长', '单腿臀桥', '手提箱走 20m'],
  ['每日核心时长', '28 分钟', '22 分钟', '22 分钟', '22 分钟', '20 分钟'],
]);

L('## 04 安全闸门', '');
L('### 4.1 三级决策树', '');
tbl(['本周情况', '怎么做'], painTree);
L('### 4.2 红线清单', '');
tbl(['信号', '处置'], redFlags);
L('### 4.3 永久排除的动作', '');
tbl(['动作', '为什么排除'], forbidden);
L('### 4.4 开练前 60 秒自查', '');
L('- 今天腰的感觉（NRS 0-10）比上周一高还是低？', '- 有没有新的腿部症状（麻/刺/放射/无力）？', '- 昨晚睡眠是否 ≥6.5 小时？不够 → 主项 -1 组、RPE -1。', '- 90/90 呼吸能不能 360° 撑开肋骨？不能 → 先做 5 分钟猫牛+呼吸。', '');

L('## 05 四个训练日详表', '');
L('参数列 B1/B2/B3/B4 对应 W1-4 / W5-8 / W9-12 / W13-16，只做你当前那一列。', '');
days.forEach((d) => {
  L(`### ${d.code} · ${d.name}`, '');
  L(`\`⏱ ${d.time}\` ｜ ${d.tags.join(' · ')}`, '');
  d.blocks.forEach((b) => {
    L(`**${b.name}（${b.time}）**`, '');
    L('| 动作 | B1 W1-4 | B2 W5-8 | B3 W9-12 | B4 W13-16 | 节奏 / 要点 |');
    L('|---|---|---|---|---|---|');
    b.items.forEach((it) => {
      const cue = `*${it.t}* ${it.c}` + (it.a ? `　<br>替代：${it.a}` : '');
      L(`| **${it.n}** | ${it.p[0]} | ${it.p[1]} | ${it.p[2]} | ${it.p[3]} | ${cue} |`);
    });
    L('');
  });
});

L(`## 06 ${dessert.name}`, '');
L(`\`⏱ ${dessert.time}\``, '');
L(`> ${dessert.note}`, '');
dessert.blocks.forEach((b) => {
  L(`**${b.name}（${b.time}）**`, '');
  tbl(['动作', 'B1', 'B2', 'B3', 'B4', '要点'], b.items.map((it) => [it.n, it.p[0], it.p[1], it.p[2], it.p[3], `*${it.t}* ${it.c}`]));
});

L('## 07 核心动作库', '');
coreLib.forEach((c) => {
  L(`### ${c.cat}`, '');
  L(`> ${c.why}`, '');
  tbl(['动作', '建议组次', '要点'], c.items.map((i) => [i.n, i.p, i.c]));
});

